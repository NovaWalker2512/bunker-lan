def create_character(rng: Random) -> dict[str, str]:
    """Генерирует случайные характеристики персонажа.

    Args:
        rng: Генератор случайных чисел.

    Returns:
        Словарь, где ключами являются категории характеристик,
        а значениями — выбранные характеристики персонажа.

    Raises:
        TypeError: Если передан не генератор Random.
    """
    if not isinstance(rng, Random):
        raise TypeError("Необходимо передать генератор Random.")

    return {
        category: rng.choice(CARD_DECK[category])
        for category in CATEGORIES
    }
